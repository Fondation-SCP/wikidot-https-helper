use clap::Parser;
use clap::Subcommand;
use indicatif::ProgressBar;
use indicatif::ProgressStyle;
use rayon::ThreadPoolBuilder;
use rayon::iter::IntoParallelIterator;
use rayon::iter::IntoParallelRefIterator;
use rayon::iter::ParallelIterator;
use reqwest::Method;
use reqwest::blocking::Client;
use reqwest::blocking::Response;
use reqwest::header::USER_AGENT;
use reqwest::redirect::Policy;
use std::collections::HashSet;
use std::error::Error;
use std::fmt::Display;
use std::net::Ipv4Addr;
use std::net::SocketAddr;
use std::net::ToSocketAddrs;
use std::path::PathBuf;

mod from_pages;

#[derive(Parser)]
struct Cli {
    /// The path to the SQLite database that contains the cached host sets.
    #[arg(long, default_value = "wikidot-https-helper-cache.sqlite")]
    cache_db: PathBuf,
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    Parse {
        /// The path to the SQLite database generated by `wikidot-css-extractor`.
        db: PathBuf,
        /// The Wikidot site handle (e.g. `scp-wiki`)
        site: String,
    },
    Check,
    Find {
        /// The host that is being looked for.
        host: String,
    },
}

fn main() {
    let args = Cli::parse();
    match args.command {
        Command::Parse { db, site } => {
            from_pages::get_matches(&site, &db, &args.cache_db);
        }
        Command::Check => {
            let wikidot_addresses = [
                Ipv4Addr::new(107, 20, 139, 170),
                Ipv4Addr::new(107, 20, 139, 176),
            ];

            let hosts: HashSet<String> = from_pages::get_cached_matches(&args.cache_db)
                .into_keys()
                .collect();
            let progress_bar = ProgressBar::new(hosts.len() as u64).with_style(
                ProgressStyle::with_template(
                    "Discriminating Wikidot hostnames {wide_bar} {pos}/{len}",
                )
                .expect("Failed to create the template for the DNS lookup progress bar"),
            );
            let (wikidot_hosts, hosts): (HashSet<String>, HashSet<String>) =
                hosts.into_par_iter().partition(|host| {
                    if let Ok(addrs) = (host as &str, 443).to_socket_addrs() {
                        for addr in addrs {
                            if let SocketAddr::V4(socket) = addr
                                && wikidot_addresses.contains(socket.ip())
                            {
                                progress_bar.inc(1);
                                return true;
                            }
                        }
                    }

                    progress_bar.inc(1);
                    false
                });

            let client = Client::builder()
                .redirect(Policy::none())
                .build()
                .expect("Failed to create the HTTP client");
            let thread_pool = ThreadPoolBuilder::new()
                .num_threads(64)
                .build()
                .expect("Failed to create the thread pool for HTTPS requests");
            let wikidot_thread_pool = ThreadPoolBuilder::new()
                .num_threads(4) // this is to avoid being rate-limited by Wikidot, since many hostnames actually lead there
                .build()
                .expect("Failed to create the thread pool for Wikidot HTTPS requests");

            let progress_bar = ProgressBar::new((hosts.len() + wikidot_hosts.len()) as u64)
                .with_style(
                    ProgressStyle::with_template("Sending HTTPS requests {wide_bar} {pos}/{len}")
                        .expect("Failed to create the template for the host check progress bar"),
                );
            rayon::join(
                || thread_pool.install(|| work(&hosts, &progress_bar, &client)),
                || wikidot_thread_pool.install(|| work(&wikidot_hosts, &progress_bar, &client)),
            );

            // TODO:
            // - flag CSS deps (need GET 200 with correct MIME "Content-Type: text/css")
        }
        Command::Find { host } => {
            let hosts = from_pages::get_cached_matches(&args.cache_db);
            match hosts.get(&host) {
                None => println!("No matches"),
                Some(pages) => {
                    for from_pages::PageAsMatchSet { slug, matches } in pages {
                        println!("{}: {:#?}", slug, matches);
                    }
                }
            }
        }
    }
}

fn work(hosts: &HashSet<String>, progress_bar: &ProgressBar, client: &Client) {
    hosts.par_iter().for_each(|host| {
        match make_request(&client, host) {
            Ok(response) => handle_response(
                &client,
                Host::OriginalHost(host.to_owned()),
                &Method::HEAD,
                &response,
                &progress_bar,
            ),
            Err(error) => progress_bar.println(error),
        }
        progress_bar.inc(1);
    });
}

fn make_request(client: &Client, host: &str) -> Result<Response, String> {
    let url = if host.starts_with("https://") {
        host
    } else {
        &format!("https://{}", host)
    };

    client
        .head(url)
        .send()
        .map_err(|error| request_error_msg(host, error))
}

fn request_error_msg(host: &str, error: reqwest::Error) -> String {
    if error.is_dns() {
        format!("{}: DNS error", host)
    } else if error.is_connect() {
        format!(
            "{}: connection error{}",
            host,
            error
                .source()
                .map(|src| format!(" ({:?})", src))
                .unwrap_or_default()
        )
    } else if error.is_timeout() {
        format!("{}: timeout", host)
    } else {
        format!("{}: weird error ({:?})", host, error)
    }
}

enum Host {
    OriginalHost(String),
    Redirected { depth: u8, original_host: String },
}

impl Display for Host {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::OriginalHost(host) => f.write_str(host),
            Self::Redirected { original_host, .. } => f.write_str(original_host),
        }
    }
}

impl Host {
    fn recur(self) -> Self {
        match self {
            Self::OriginalHost(host) => Self::Redirected {
                depth: 1,
                original_host: host,
            },
            Self::Redirected {
                depth,
                original_host,
                ..
            } => Self::Redirected {
                depth: depth + 1,
                original_host,
            },
        }
    }
}

fn make_get_request(client: &Client, host: &Host) -> Result<Response, String> {
    client
        .get(format!("https://{}", host))
        .header(
            USER_AGENT,
            "Mozilla/5.0 (X11; Linux x86_64; rv:156.0) Gecko/20100101 Firefox/156.0",
        )
        .send()
        .map_err(|error| request_error_msg(&host.to_string(), error))
}

fn handle_response(
    client: &Client,
    host: Host,
    method: &Method,
    response: &Response,
    bar: &ProgressBar,
) {
    let status = response.status();
    if !status.is_success() {
        match u16::from(status) {
            403 | 405 | 501 => {
                if method == Method::HEAD {
                    match make_get_request(client, &host) {
                        Ok(response) => handle_response(client, host, &Method::GET, &response, bar),
                        Err(error) => bar.println(error),
                    }
                } else {
                    bar.println(format!("{}: code {} even on GET", host, u16::from(status)))
                }
            }
            301 | 302 | 307 | 308 => {
                if let Host::Redirected { depth, .. } = host
                    && depth > 10
                {
                    bar.println(format!("{}: too many redirections", host))
                } else {
                    match response.headers().get("Location") {
                        Some(location) => match location.to_str() {
                            Ok(location) => {
                                if location.starts_with("http:") {
                                    bar.println(format!("{}: redirected to HTTP", host))
                                } else {
                                    match make_request(client, location) {
                                        Ok(response) => handle_response(
                                            client,
                                            host.recur(),
                                            &Method::HEAD,
                                            &response,
                                            bar,
                                        ),
                                        Err(error) => bar.println(error),
                                    }
                                }
                            }
                            Err(error) => {
                                bar.println(format!(
                            "{}: redirection code ({}) with an invalid Location header ({:#?})",
                            host,
                            u16::from(status),
                            error
                        ));
                            }
                        },
                        None => {
                            bar.println(format!(
                                "{}: redirection code ({}) without a Location header",
                                host,
                                u16::from(status)
                            ));
                        }
                    }
                }
            }
            // TODO: on other 4xx: compare with http:// to be sure
            // 429 should be surfaced, not much we can do about it
            other if status.is_client_error() => bar.println(format!("{}: code {}", host, other)),
            other => bar.println(format!("Weird response from {}: code {}", host, other)),
        }
    }
}
