use rayon::iter::IntoParallelRefMutIterator;
use rayon::iter::ParallelIterator;
use rusqlite::params;
use rusqlite::OpenFlags;
use std::hash::DefaultHasher;
use std::hash::Hasher;
use std::sync::mpsc;
use std::sync::mpsc::Sender;
use std::time::Duration;
use std::time::Instant;
use std::{borrow::Cow, path::PathBuf};

use clap::Parser;
use ftml::{
    data::{PageInfo, ScoreValue},
    layout::Layout,
    prelude::{WikitextMode, WikitextSettings},
};
use rusqlite::Connection;

#[derive(Parser)]
struct Cli {
    /// The path to the SQLite database generated by `wikidot-css-extractor`.
    db: PathBuf,
    /// The Wikidot site handle (e.g. `scp-wiki`)
    site: String,
    /// The path to the SQLite database that contains the cached FTML syntax trees.
    #[arg(long, default_value = "wikidot-https-helper-cache.sqlite")]
    cache_db: PathBuf,
}

struct Page {
    url: String,
    slug: String,
    source: String,
    title: String,
    category: String,
}

fn main() {
    let args = Cli::parse();

    let db = Connection::open_with_flags(args.db, OpenFlags::SQLITE_OPEN_READ_ONLY)
        .expect("Failed to open a connection to the database");

    let mut pages = {
        let mut stmt = db
            .prepare("SELECT * FROM pages WHERE url LIKE ?")
            .expect("Failed to prepare SQL `SELECT` statement");
        let pattern = format!("http://{}.wikidot.com/%", args.site);
        stmt.query_map([pattern], |row| {
            Ok(Page {
                url: row.get("url")?,
                slug: row.get("slug")?,
                source: row.get("source")?,
                title: row.get("title")?,
                category: row.get("category")?,
            })
        })
        .expect("Failed to query the database")
        .map(|maybe_page| maybe_page.expect("Failed to iterate through a page"))
        .collect::<Vec<_>>()
    };

    let parse_settings = WikitextSettings::from_mode(WikitextMode::Page, Layout::Wikidot);

    let npages = pages.len() as u64;

    let cache_queue = spawn_cache_thread(args.cache_db);

    let nwarnings: usize = pages
        .par_iter_mut()
        .progress_count(npages)
        .map(|page| {
            let page_info = PageInfo {
                page: Cow::Borrowed(&page.slug),
                category: match &*page.category {
                    "_default" => None, // according to docs: https://docs.rs/ftml/1.41.0/ftml/data/struct.PageInfo.html#structfield.category
                    category => Some(Cow::Borrowed(category)),
                },
                site: Cow::Borrowed(&args.site),
                title: Cow::Borrowed(&page.title),
                alt_title: None, // not worth the hassle to try to fetch it
                score: ScoreValue::Integer(0), // same
                tags: Vec::new(), // same
                language: Cow::Borrowed("en"), // same
            };

            let mut hasher = DefaultHasher::new();
            hasher.write(page.source.as_bytes());
            let hash = hasher.finish() as i64;

            todo!("check cache for hash before reparsing");

            ftml::preprocess(&mut page.source);
            let tokens = ftml::tokenize(&page.source);
            let (tree, warnings) = ftml::parse(&tokens, &page_info, &parse_settings).into();
            cache_queue
                .send(Cacheable {
                    url: page.url.clone(),
                    hash,
                    blob: todo!("serialize tree using postcard"),
                })
                .expect("The caching thread is gone");
            warnings.len()
        })
        .sum();

    println!("{} warnings generated", nwarnings);
}

struct Cacheable {
    url: String,
    hash: i64, // u64 does not implement rusqlite::types::ToSql
    blob: Vec<u8>,
}

fn spawn_cache_thread(cache_db_path: PathBuf) -> Sender<Cacheable> {
    let (tx, rx) = mpsc::channel();
    std::thread::spawn(move || {
        let mut db = Connection::open(cache_db_path)
            .expect("Failed to open a connection to the cache database");
        db.execute("CREATE TABLE IF NOT EXISTS cache (url TEXT PRIMARY KEY, hash BLOB NOT NULL, syntax_tree BLOB NOT NULL)", []).expect("Failed to ensure that the cache table exists");

        let interval = Duration::from_secs(1);
        let mut next_run = Instant::now();

        loop {
            let start_time = Instant::now();
            std::thread::sleep(next_run.saturating_duration_since(start_time));

            if let Ok(transaction) = db.transaction() {
                for Cacheable { url, hash, blob } in rx.try_iter() {
                    transaction.execute("INSERT INTO cache(url, hash, syntax_tree) VALUES(?, ?, ?) ON CONFLICT(url) DO UPDATE SET hash=?, syntax_tree=?",params![url,hash, blob, hash, blob]).expect("Failed to cache a row");
                }
                transaction
                    .commit()
                    .expect("Failed to commit a cache transaction");
            }

            next_run = start_time + interval;
        }
    });
    tx
}
